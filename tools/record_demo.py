"""Record the demo's clips: the first 30 s of each level as its replay test plays it (the
buttons the game read in each gameplay update), written as C arrays for
src/game_state/demo.c.

    python tools/record_demo.py [rom] -o src/game_state/demo_clips.h

"make demo" runs it on obj/ApexLab.gb. A clip is a list of (buttons, updates) pairs,
1-255 updates each. The game has no randomness, so the same buttons from a level's start
play out the same way again. A replay that finishes sooner (the exit, or KERNEL's last
upload) is cut a second before that, so the demo never completes a level.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

from gamelib import COREGAMELOOP, LEVEL_1, LEVEL_2, LEVEL_3, LEVEL_4, LEVEL_5, Game, Pilot, boot  # noqa: E402
from test_boss import KernelPilot, beat_kernel  # noqa: E402
from test_level_1 import play_level_1  # noqa: E402
from test_level_2 import play_level_2  # noqa: E402
from test_level_3 import play_level_3  # noqa: E402
from test_level_4 import play_level_4  # noqa: E402

CLIP_UPDATES = 1800          # 30 s at 60 fps
END_MARGIN_UPDATES = 60      # a clip that reaches the level's end stops 1 s before it
# The game's levels in order: the level index, the pilot, and the replay that plays it.
LEVELS = [(LEVEL_1, Pilot, play_level_1), (LEVEL_2, Pilot, play_level_2), (LEVEL_3, Pilot, play_level_3),
          (LEVEL_4, Pilot, play_level_4), (LEVEL_5, KernelPilot, beat_kernel)]


class ClipDone(Exception):
    pass


def record_clip(rom: Path, level: int, pilot_class, play) -> list[int]:
    """The buttons of the level's first CLIP_UPDATES gameplay updates, one per update."""
    pyboy = boot(rom, "dmg")
    game = Game(pyboy, "dmg", ROOT / "tests" / "out", "record_demo", level)
    buttons = []

    def at_update(_):
        current, previous = game.u8("_joypad_current"), game.u8("_joypad_previous")
        assert previous == (buttons[-1] if buttons else 0), "the last update's buttons changed in between"
        buttons.append(current)

    pyboy.hook_register(None, "_main_game_loop", at_update, None)

    def frame(pilot) -> None:
        pilot_class.frame(pilot)
        if len(buttons) >= CLIP_UPDATES:
            raise ClipDone

    try:
        game.wait_for_state(COREGAMELOOP, timeout=600)
        play(type("RecordingPilot", (pilot_class,), {"frame": frame})(game))
        return buttons[:-END_MARGIN_UPDATES]    # the level was done: stop short of the end
    except ClipDone:
        return buttons[:CLIP_UPDATES]
    finally:
        pyboy.stop(save=False)


def run_lengths(buttons: list[int]) -> list[tuple[int, int]]:
    """(buttons, updates) pairs, at most 255 updates each."""
    pairs = []
    for value in buttons:
        if pairs and pairs[-1][0] == value and pairs[-1][1] < 255:
            pairs[-1] = (value, pairs[-1][1] + 1)
        else:
            pairs.append((value, 1))
    return pairs


def write_clips(clips: list[list[tuple[int, int]]], path: Path) -> None:
    """The clips as C arrays in a header that only demo.c includes, so they share its ROM
    bank and it reads them without switching banks."""
    lines = ["// Generated by tools/record_demo.py from the level replays in tests/. Don't edit:",
             "// run \"make demo\" after a change that alters how a level plays. Included by",
             "// src/game_state/demo.c only: per level, (buttons, updates) pairs.",
             "#ifndef DEMO_CLIPS_H", "#define DEMO_CLIPS_H", ""]
    for level, pairs in enumerate(clips):
        values = ", ".join(f"0x{b:02X},{n}" for b, n in pairs)
        lines.append(f"static const uint8_t clip_{level + 1}[] = {{ {values} }};")
    lines += ["", "static const uint8_t* const demo_clips[] = { "
              + ", ".join(f"clip_{level + 1}" for level in range(len(clips))) + " };",
              "static const uint8_t* const demo_clip_ends[] = { "
              + ", ".join(f"clip_{level + 1} + sizeof(clip_{level + 1})" for level in range(len(clips))) + " };",
              "", "#endif", ""]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("rom", nargs="?", default=str(ROOT / "obj" / "ApexLab.gb"))
    parser.add_argument("-o", "--out", default=str(ROOT / "src" / "game_state" / "demo_clips.h"))
    args = parser.parse_args()
    clips = []
    for level, pilot_class, play in LEVELS:
        pairs = run_lengths(record_clip(Path(args.rom), level, pilot_class, play))
        print(f"level {level + 1}: {sum(n for _, n in pairs)} updates, {2 * len(pairs)} bytes")
        clips.append(pairs)
    write_clips(clips, Path(args.out))


if __name__ == "__main__":
    main()
